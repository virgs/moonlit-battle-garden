export const characterIds = ['champignon', 'andromoss', 'captain-bramble', 'duskmantle', 'sprig'] as const;
export type CharacterId = typeof characterIds[number];
export function isCharacterId(value: unknown): value is CharacterId { return typeof value === 'string' && (characterIds as readonly string[]).includes(value); }
export type Difficulty = 'easy' | 'medium' | 'hard';
export type PlayerId = 0 | 1;
export type TargetKind = 'mole' | 'rabbit' | 'star';
export type Phase = 'countdown' | 'playing' | 'round-over' | 'match-over';
export type Target = { id: number; kind: TargetKind; born: number; expires: number; origin?: 'natural' | 'star' | 'magic'; armor?: number; persistentArmor?: boolean; missBonus?: number; extended?: boolean };
export type PendingSpell = { tier: number; at: number; from: PlayerId };
export type Player = {
  character: CharacterId;
  score: number;
  stars: number;
  wins: number;
  holes: (Target | null)[];
  spawned: number;
  nextSpawn: number;
  nextDecoy: number;
  nextCast: number;
  mistakeShield: number;
  shieldTier: number;
  shieldUntil: number;
  magicShieldUntil: number;
  invasionUntil: number;
  decoysUntil: number;
  armorUntil: number;
  armorHits: number;
  armorCharges: number;
  tinCharges: number;
  armorTier: number;
  markUntil: number;
  markCharges: number;
  markBonus: number;
  markTier: number;
  camouflageUntil: number;
  drainUntil: number;
  tendingUntil: number;
  automationUntil: number;
  automationColumns: number[];
  sweepUntil: number;
  sweepColumns: number[];
  sweepTier: number;
  nextSweep: number;
  automationTier: number;
  nextAutomation: number;
  pending: PendingSpell[];
  message: string;
  messageUntil: number;
};
export type MatchState = {
  phase: Phase;
  time: number;
  round: number;
  roundStart: number;
  countdownUntil: number;
  players: [Player, Player];
  winner: PlayerId | null;
  result: string;
  paused: boolean;
  casting: { player: PlayerId; tier: number; remainingMs: number } | null;
};
export type SpellTier = 1 | 2 | 3 | 4;
export type IsolatedCastingPolicy = 'immediate' | 'opportunity';
export type MatchOptions = {
  /** Offline fixed-duration reaction diagnostic: disable casts and score victory. */
  diagnosticMode?: 'reaction';
  isolatedCastingPolicy?: IsolatedCastingPolicy;
  /** Offline diagnostic only: capacity/casting cost equals this tier. */
  isolatedSpellTier?: SpellTier;
  characters: [CharacterId, CharacterId];
  mode: 'ai' | 'local' | 'online';
  difficulty: Difficulty;
  seed: number;
};
export type GameAction = { type: 'hit'; player: PlayerId; hole: number } | { type: 'cast'; player: PlayerId };
export type GameEvent = { id: number; time: number; round: number; player: PlayerId; kind: 'hit' | 'star' | 'penalty' | 'shield' | 'cast'; hole?: number; tier?: number; targetKind?: TargetKind; reason?: 'empty' | 'miss' | 'rabbit' };
